"""Builds and validates the bundled guide JSON in app/src/main/assets/guides/.

    python3 tools/content/build_guides.py          # write the JSON files
    python3 tools/content/build_guides.py --check  # fail if the JSON is out of date or invalid
"""
import json
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from common import UPDATED  # noqa: E402
from cookbook import COOKBOOK  # noqa: E402
from first_aid import FIRST_AID  # noqa: E402
from survival import SURVIVAL  # noqa: E402

OUT = HERE.parent.parent / "app" / "src" / "main" / "assets" / "guides"
ID = re.compile(r"^[a-z0-9][a-z0-9-]*$")
REQUIRED_FIRST_AID = ["recognise", "now", "avoid", "warning", "help", "limits"]


def collection(c):
    return {"id": c["id"], "title": c["title"], "formatVersion": 1, "updated": UPDATED, "categories": c["categories"]}


def check_article(a, problems, where):
    if not ID.match(a["id"]):
        problems.append(f"{where}: bad id {a['id']}")
    if not a["title"] or not a["summary"]:
        problems.append(f"{where}: title and summary are required")
    if not re.match(r"^\d{4}-\d{2}-\d{2}$", a["updated"]):
        problems.append(f"{where}: bad date")
    if a["review"]["status"] not in ("pending", "reviewed"):
        problems.append(f"{where}: bad review status")
    if a["review"]["status"] == "reviewed" and not (a["review"].get("reviewedBy") and a["review"].get("reviewedOn")):
        problems.append(f"{where}: 'reviewed' needs reviewedBy and reviewedOn")
    ids = [s["id"] for s in a["sections"]]
    if len(ids) != len(set(ids)):
        problems.append(f"{where}: duplicate section ids")
    for s in a["sections"]:
        for item in s["items"]:
            if len(item) > 400:
                problems.append(f"{where}/{s['id']}: item too long for a stressful moment")


def validate():
    problems = []
    seen = set()
    for c in (FIRST_AID, SURVIVAL):
        for cat in c["categories"]:
            for a in cat["articles"]:
                where = f"{c['id']}/{a['id']}"
                if where in seen:
                    problems.append(f"duplicate {where}")
                seen.add(where)
                check_article(a, problems, where)
                if c is FIRST_AID:
                    ids = [s["id"] for s in a["sections"]]
                    missing = [r for r in REQUIRED_FIRST_AID if r not in ids]
                    if missing:
                        problems.append(f"{where}: missing sections {missing}")
                    if not a["references"]:
                        problems.append(f"{where}: first-aid articles need references")
                    if not any("112" in i for s in a["sections"] for i in s["items"]):
                        problems.append(f"{where}: should say when to call 112")
    recipe_ids = set()
    for r in COOKBOOK["recipes"]:
        if r["id"] in recipe_ids:
            problems.append(f"duplicate recipe {r['id']}")
        recipe_ids.add(r["id"])
        if not (r["ingredients"] and r["steps"] and r["equipment"]):
            problems.append(f"recipe {r['id']}: ingredients, steps and equipment are required")
        if r["servings"] <= 0 or r["waterMl"] < 0:
            problems.append(f"recipe {r['id']}: bad numbers")
    for a in COOKBOOK["safety"]:
        check_article(a, problems, f"cookbook/{a['id']}")
    return problems


def review_status():
    lines = ["# Content review status", "", "Generated by tools/content/build_guides.py. Do not edit by hand.", ""]

    def table(title, articles):
        lines.extend([f"## {title}", "", "| Article | Status | References |", "|---|---|---|"])
        for a in articles:
            review = a["review"]
            st = "Reviewed " + review.get("reviewedOn", "") if review["status"] == "reviewed" else "Pending"
            refs = "; ".join(r["publisher"] for r in a["references"]) or "—"
            lines.append(f"| {a['title']} | {st} | {refs} |")
        lines.append("")

    table("First Aid", [a for c in FIRST_AID["categories"] for a in c["articles"]])
    table("Survival Handbook", [a for c in SURVIVAL["categories"] for a in c["articles"]])
    table("Food and water safety", COOKBOOK["safety"])
    lines.append(f"Recipes: {len(COOKBOOK['recipes'])}, written for this project; food-safety notes follow the articles above.")
    return "\n".join(lines) + "\n"


def outputs():
    return {
        "first_aid.json": collection(FIRST_AID),
        "survival.json": collection(SURVIVAL),
        "cookbook.json": COOKBOOK,
    }


def main():
    problems = validate()
    if problems:
        print("\n".join(problems))
        sys.exit(1)
    check = "--check" in sys.argv
    stale = []
    OUT.mkdir(parents=True, exist_ok=True)
    for name, data in outputs().items():
        text = json.dumps(data, ensure_ascii=False, indent=1) + "\n"
        path = OUT / name
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            path.write_text(text, encoding="utf-8")
    status = review_status()
    status_path = HERE.parent.parent / "docs" / "content-review-status.md"
    if check:
        if not status_path.exists() or status_path.read_text(encoding="utf-8") != status:
            stale.append("docs/content-review-status.md")
    else:
        status_path.write_text(status, encoding="utf-8")
    if stale:
        print("Out of date, run tools/content/build_guides.py:", ", ".join(stale))
        sys.exit(1)
    fa = sum(len(c["articles"]) for c in FIRST_AID["categories"])
    sv = sum(len(c["articles"]) for c in SURVIVAL["categories"])
    print(f"OK: {fa} first-aid articles, {sv} survival articles, {len(COOKBOOK['recipes'])} recipes, "
          f"{len(COOKBOOK['safety'])} food-safety articles")


if __name__ == "__main__":
    main()
